package com.edumanage;
public class Student {
    private int id, deptId, semester; private String code, name, gender, dob, email, phone, address, dept, status;
    public int getId(){return id;} public void setId(int v){id=v;}
    public int getDeptId(){return deptId;} public void setDeptId(int v){deptId=v;}
    public int getSemester(){return semester;} public void setSemester(int v){semester=v;}
    public String getCode(){return code;} public void setCode(String v){code=v;}
    public String getName(){return name;} public void setName(String v){name=v;}
    public String getGender(){return gender;} public void setGender(String v){gender=v;}
    public String getDob(){return dob;} public void setDob(String v){dob=v;}
    public String getEmail(){return email;} public void setEmail(String v){email=v;}
    public String getPhone(){return phone;} public void setPhone(String v){phone=v;}
    public String getAddress(){return address;} public void setAddress(String v){address=v;}
    public String getDept(){return dept;} public void setDept(String v){dept=v;}
    public String getStatus(){return status;} public void setStatus(String v){status=v;}
}
